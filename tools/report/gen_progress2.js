function head(s, title, kicker) {
  if (kicker) s.addText(kicker, { x: 0.55, y: 0.34, w: 12.2, h: 0.3, fontSize: 13, color: BLUE, bold: true, fontFace: FONT });
  s.addText(title, { x: 0.55, y: kicker ? 0.62 : 0.45, w: 12.2, h: 0.62, fontSize: 27, bold: true, color: INK, fontFace: FONT });
  s.addShape(p.ShapeType.line, { x: 0.55, y: kicker ? 1.30 : 1.15, w: 12.2, h: 0, line: { color: RULE, width: 1 } });
}
const bullets = (s, items, o = {}) =>
  s.addText(items.map(t => {
    const txt = typeof t === "string" ? t : t.t;
    const sub = /^\s*(·|→)/.test(txt);          // 子項目：不重複打點,縮排一層
    const hi = typeof t === "object" && t.hi;
    const col = typeof t === "object" && t.color;
    return {
      text: sub ? "      " + txt : txt,
      options: { bullet: sub ? false : { indent: 18 }, breakLine: true,
                 fontSize: o.size || 15.5, color: col || (hi ? BLUE : INK2), bold: !!hi,
                 indentLevel: sub ? 1 : 0, paraSpaceAfter: sub ? 4 : 7 },
    };
  }), { x: o.x ?? 0.75, y: o.y ?? 1.55, w: o.w ?? 12.0, h: o.h ?? 5.4, fontFace: FONT, valign: "top" });
const note = (s, t, y) =>
  s.addText(t, { x: 0.75, y: y ?? 6.55, w: 11.9, h: 0.55, fontSize: 12.5, italic: true, color: INK2, fontFace: FONT });

// 表格：第一列為表頭。欄寬用 colW 指定。
function table(s, rows, o = {}) {
  const body = rows.map((r, i) =>
    r.map(c => {
      const txt = typeof c === "string" ? c : c.t;
      return {
        text: txt,
        options: {
          fontSize: o.size || 13, fontFace: FONT, valign: "middle",
          bold: i === 0 || (typeof c === "object" && c.b),
          color: i === 0 ? "FFFFFF" : ((typeof c === "object" && c.color) || INK2),
          fill: i === 0 ? { color: "3E4C5E" } : { color: i % 2 ? "FFFFFF" : "F6F7F9" },
          align: "left",
        },
      };
    }));
  s.addTable(body, {
    x: o.x ?? 0.75, y: o.y ?? 1.6, w: o.w ?? 11.9, colW: o.colW,
    border: { type: "solid", color: RULE, pt: 0.5 }, rowH: o.rowH || 0.34,
    margin: 0.06,
  });
}

