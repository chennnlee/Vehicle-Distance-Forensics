function defList(s, items, y0, o = {}) {
  const step = o.step ?? 0.85, kw = o.kw ?? 2.4, x0 = o.x ?? 0.9, wAll = o.w ?? 11.6;
  items.forEach(([a, b], i) => {
    const y = y0 + i * step;
    s.addShape(p.ShapeType.line, { x: x0, y: y + step - 0.08, w: wAll, h: 0, line: { color: LINE, width: 1 } });
    s.addText(a, { x: x0, y, w: kw, h: step - 0.12, fontSize: o.keySize ?? 14.5, bold: true,
                   color: ACCENT, fontFace: FONT, valign: "top" });
    s.addText(b, { x: x0 + kw + 0.2, y, w: wAll - kw - 0.2, h: step - 0.1, fontSize: o.size ?? 13,
                   color: INK, fontFace: FONT, valign: "top", lineSpacingMultiple: 1.22 });
  });
}
function stack(s, items, y0, o = {}) {           // defList with its own height per item
  const kw = o.kw ?? 1.4, x0 = o.x ?? 0.9, wAll = o.w ?? 11.6;
  let y = y0;
  items.forEach(([a, b, hgt]) => {
    s.addText(a, { x: x0, y, w: kw, h: hgt - 0.12, fontSize: o.keySize ?? 14.5, bold: true,
                   color: ACCENT, fontFace: FONT, valign: "top" });
    s.addText(b, { x: x0 + kw + 0.15, y, w: wAll - kw - 0.15, h: hgt - 0.1, fontSize: o.size ?? 13,
                   color: INK, fontFace: FONT, valign: "top", lineSpacingMultiple: 1.22 });
    y += hgt;
    s.addShape(p.ShapeType.line, { x: x0, y: y - 0.08, w: wAll, h: 0, line: { color: LINE, width: 1 } });
  });
}
