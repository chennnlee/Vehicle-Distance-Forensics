// 表格：第一列為表頭。欄寬用 colW 指定。
function table(s, rows, o = {}) {
  const body = rows.map((r, i) =>
    r.map(c => {
      const txt = typeof c === "string" ? c : c.t;
      return {
        text: txt,
        options: {
          fontSize: o.size || 13, fontFace: FONT, valign: "middle",
          bold: i === 0 || (typeof c === "object" && c.b),
          color: i === 0 ? "FFFFFF" : ((typeof c === "object" && c.color) || INK2),
          fill: i === 0 ? { color: "3E4C5E" } : { color: i % 2 ? "FFFFFF" : "F6F7F9" },
          align: "left",
        },
      };
    }));
  s.addTable(body, {
    x: o.x ?? 0.75, y: o.y ?? 1.6, w: o.w ?? 11.9, colW: o.colW,
    border: { type: "solid", color: RULE, pt: 0.5 }, rowH: o.rowH || 0.34,
    margin: 0.06,
  });
}

